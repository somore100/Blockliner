"""Small pure helpers for exporting code: file ending, header comment, private temp folder."""
import os
import tempfile

import language_switch

DEFAULT_TOKEN = "#"


def file_ending(language, extensions):
    """'.py' for python, '.rs' for rust... or '.txt' when the language has none."""
    return language_switch.extension_for(language, extensions) or ".txt"


def comment_line(token, text):
    """One comment line in the language's own comment style. '<!--' (HTML)
    needs a closing '-->' so it is wrapped; every other token is a prefix."""
    token = token or DEFAULT_TOKEN
    if token == "<!--":
        return f"<!-- {text} -->"
    return f"{token} {text}"


def header(token, language, extra=None):
    """The 'Generated by Blockliner' banner as comments valid in that language,
    ending with one blank line. extra is an optional list of more lines."""
    lines = [comment_line(token, "Generated by Blockliner - by domore100"),
             comment_line(token, f"Language: {language}")]
    for line in extra or []:
        lines.append(comment_line(token, line))
    return "\n".join(lines) + "\n\n"


def private_folder(prefix="blockliner_"):
    """A new folder only this user can open, for scripts that are about to be run
    (a fixed name in the shared temp folder could be swapped for a link)."""
    return tempfile.mkdtemp(prefix=prefix)


def write_text(path, text):
    """Write text as UTF-8, whatever the system's language setting is."""
    with open(path, "w", encoding="utf-8") as f:
        f.write(text)
