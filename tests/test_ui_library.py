"""UI libraries (packs): several per language, a default, a pick rule for new UI
nodes, a description for every widget, and a second library that generates
runnable code. Pure, no Tk."""
import os, sys
from unittest import mock
sys.path.insert(0, os.path.join(os.path.dirname(os.path.abspath(__file__)), ".."))
import ui_gen, ui_node, ui_pack
from ui_tree import UITree

ROOT = os.path.join(os.path.dirname(os.path.abspath(__file__)), "..", "ui_packs")
fails = []
def check(name, cond):
    print(f"[{'OK' if cond else 'FAIL'}] {name}")
    if not cond:
        fails.append(name)

packs, notes = ui_pack.find_packs([ROOT], "python")
check("both Python libraries load without notes", [p.id for p in packs] == ["python/tkinter", "python/customtkinter"] and not notes)
check("tkinter stays the default", packs[0].id == "python/tkinter")
for p in packs:
    check(f"{p.id}: the library has a description", bool(p.description))
    check(f"{p.id}: every widget has a description", all(w["description"] for w in p.widgets.values()))

tk_pack, ctk_pack = packs
check("pick: only one library, no question", ui_pack.pick_pack([tk_pack]) == (tk_pack, False))
check("pick: several libraries and none used asks", ui_pack.pick_pack(packs) == (None, True))
check("pick: the file's library is reused", ui_pack.pick_pack(packs, None, ["python/customtkinter"]) == (ctk_pack, False))
check("pick: an unknown used id is ignored", ui_pack.pick_pack(packs, None, ["python/gone"]) == (None, True))
check("pick: a named library", ui_pack.pick_pack(packs, "python/tkinter") == (tk_pack, False))
check("pick: no libraries", ui_pack.pick_pack([]) == (None, False))

node = {"id": "n", "name": "UI 1", "blocks": [], "ui": {"pack": "python/customtkinter"}}
check("a UI node knows its library", ui_node.pack_id_of(node) == "python/customtkinter" and ui_node.pack_id_of({"id": "x"}) is None)

# every widget of the second library, generated and run against a stub module
tree = UITree.new(ctk_pack.id, props=ctk_pack.defaults("window"), root_name="app")
root = tree.root["id"]
frame = tree.add(root, "frame", layout={"manager": "grid", "row": 0, "column": 0})
for i, wtype in enumerate(t for t in ctk_pack.widgets if t not in ctk_pack.root_types and t != "frame"):
    wid = tree.add(frame, wtype, props=ctk_pack.defaults(wtype), layout={"manager": "grid", "row": i, "column": 0})
    for ev in ctk_pack.widget(wtype)["events"]:
        tree.set_event(wid, ev["key"], "fn1")
res = ui_gen.generate(tree, ctk_pack, handler_name={"fn1": "on_event"}.get, function_name="build_app")
text = ui_gen.render(res)
check("no problems in the customtkinter tree", res["problems"] == [])
check("it uses customtkinter, not tkinter", "import customtkinter as ctk" in text and "tk.Tk(" not in text and "ttk." not in text)
for cls in ("CTk()", "CTkFrame", "CTkLabel", "CTkButton", "CTkCheckBox", "CTkEntry", "CTkTextbox", "CTkComboBox"):
    check(f"it builds a {cls}", f"ctk.{cls.rstrip('()')}" in text)
ns = {"on_event": lambda *a: None}
stub = mock.MagicMock(name="customtkinter")
with mock.patch.dict(sys.modules, {"customtkinter": stub}):
    try:
        exec(compile(text, "<generated>", "exec"), ns)
        ran = True
    except Exception as e:
        print("   ", repr(e)); ran = False
check("the generated code compiles and runs", ran)

# a window made for one library is not generated by another
other, problems = ui_node.generate_text({"id": "n", "name": "UI", "blocks": [], "ui": tree.to_dict() if hasattr(tree, "to_dict") else {}}, tk_pack)
check("a tree is never generated by the wrong library", other is None and "made for" in problems[0])

print("ALL OK" if not fails else f"FAILURES: {fails}")
sys.exit(1 if fails else 0)
