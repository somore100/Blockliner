"""Scripted UI test (run under Xvfb): the audit's window-side fixes - renaming a function node keeps the
program working, Export & Run never runs the code, headers fit the language, late approvals are dropped,
undo history belongs to its project, user-added languages count as available."""
import contextlib
import io
import os
import sys
import tempfile
from tkinter import filedialog, messagebox

sys.path.insert(0, os.path.dirname(os.path.dirname(os.path.abspath(__file__))))

import ext_runner
import language_scaffold
import node_ports
from nodes_model import find_node_by_id, make_node
from ui import BlocklinerUI

FAILURES = []


def check(label, cond):
    print(f"[{'OK' if cond else 'FAIL'}] {label}")
    if not cond:
        FAILURES.append(label)


def settle(app):
    for _ in range(6):
        app.update_idletasks()
        app.update()


def run(app):
    code = app.code_text.get("1.0", "end")
    out = io.StringIO()
    error = None
    with contextlib.redirect_stdout(out):
        try:
            exec(compile(code, "<generated>", "exec"), {"__name__": "__generated__"})
        except Exception as e:                 # the typed greet(5) call below is expected to break after a rename
            error = e
    return out.getvalue().split(), error


class Reply:
    cancelled = False


def main():
    messagebox.askyesno = lambda *a, **k: True
    messagebox.showinfo = lambda *a, **k: None
    messagebox.showwarning = lambda *a, **k: None
    app = BlocklinerUI(initial_lang="python", languages_path="languages")
    app.geometry("1400x900+0+0")
    try:
        settle(app)
        tab = app.tabs[app.active_tab_index]

        # ---- B1: renaming a function node
        start = app.get_active_node(tab)
        start["name"], start["order"] = "start", 0
        start["blocks"][:] = [("assign_variable", {"variable": "x", "value": "1"})]
        greet = make_node("greet", node_id="gr", order=1, blocks=[
            ("func_def", {"name": "greet", "params": "n", "_children": [("print_output", {"value": "n + 1"})]})])
        caller = make_node("caller", node_id="cl", order=2, blocks=[("func_call", {"name": "greet", "args": "x"})])
        typed = make_node("typed", node_id="ty", order=3, blocks=[("print_output", {"value": "greet(5)"})])
        tab["nodes"].extend([greet, caller, typed])
        app.refresh_workspace()
        settle(app)
        before, err = run(app)
        check("before the rename the program prints 2, then 6 and None from the typed call", before == ["2", "6", "None"] and err is None)
        ok, msg, n = app.rename_node(tab, find_node_by_id(tab["nodes"], "gr"), "hello")
        settle(app)
        g = find_node_by_id(tab["nodes"], "gr")
        check("rename succeeded and changed the call and the definition", ok and n == 2)
        check("the node still holds a function of its (new) name", node_ports.has_function(g) and g["blocks"][0][1]["name"] == "hello")
        code = app.code_text.get("1.0", "end")
        check("the definition is written before its callers", code.index("def hello(") < code.index("hello(x)"))
        after, err = run(app)
        check("after the rename the generated program still prints 2 (only the typed old name is left over)",
              after == ["2"] and isinstance(err, NameError) and "greet" in str(err))
        check("calls typed as text are reported", app._rename_text_mentions == ["typed"])

        # ---- B3 / B4: Export & Run only exports, with a header that fits the language
        tmp = tempfile.mkdtemp()
        target = os.path.join(tmp, "out.py")
        filedialog.asksaveasfilename = lambda **k: target
        windows_before = len([w for w in app.winfo_children() if w.winfo_class() == "Toplevel"])
        sys.stdout = captured = io.StringIO()
        try:
            app.export_and_run()
        finally:
            sys.stdout = sys.__stdout__
        settle(app)
        windows_after = len([w for w in app.winfo_children() if w.winfo_class() == "Toplevel"])
        check("Export & Run opens no output window and runs nothing", windows_after == windows_before and captured.getvalue() == "")
        with open(target, encoding="utf-8") as f:
            text = f.read()
        check("the exported file starts with a # header for python", text.startswith("# Generated by Blockliner"))
        filedialog.asksaveasfilename = lambda **k: ""
        app.export_and_run()
        settle(app)
        check("cancelling the file dialog still runs nothing", windows_after == len([w for w in app.winfo_children() if w.winfo_class() == "Toplevel"]))
        check("Export & Run has no run code of its own any more", "exec(" not in __import__("inspect").getsource(type(app).export_and_run))
        check("the terminal run uses a private folder", os.path.isdir(app.run_folder()) and app.run_folder() == app.run_folder())

        # ---- C3: an approval that arrives after the caller gave up changes nothing
        reply = Reply()
        reply.cancelled = True
        app._edit_reply = reply
        before_blocks = repr(tab["nodes"])
        answer = app._apply_project_edits("An AI tool", [{"op": "rename_node", "node": "cl", "name": "renamed"}], confirm=True)
        app._edit_reply = None
        check("a late edit is refused and the project is unchanged",
              isinstance(answer, ext_runner.ExtensionError) and answer.code == "busy" and repr(tab["nodes"]) == before_blocks)
        answer = app._apply_project_edits("An AI tool", [{"op": "rename_node", "node": "cl", "name": "renamed"}], confirm=True)
        check("the same edit goes through when the caller is still waiting", isinstance(answer, dict) and answer.get("ok"))

        # ---- C5: undo history lives on the project
        ws = app.workspaces[app.active_ws_index]
        check("the undo stack is kept on its workspace", app._undo_stack() is ws["undo_stack"])

        # ---- C9: a language the user added is an available language
        scratch = tempfile.mkdtemp()
        folder = language_scaffold.write_starter(app.languages_path, "zzaudit_lang")
        try:
            check("a user-added language is listed as available", "zzaudit_lang" in app.get_available_languages())
        finally:
            import shutil
            shutil.rmtree(folder, ignore_errors=True)
    finally:
        app.destroy()
    print("ALL OK" if not FAILURES else f"{len(FAILURES)} FAILED")
    sys.exit(1 if FAILURES else 0)


if __name__ == "__main__":
    main()
